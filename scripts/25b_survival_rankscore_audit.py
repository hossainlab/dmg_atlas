#!/usr/bin/env python
"""Phase 7 / step 25b - survival re-analysis on the CORRECTED metaprogram families (audit P7-07, P7-08, P7-09).

Why this script exists instead of a plain re-run of 25_openpedcan_survival.py:
  25_openpedcan_survival.py fits Cox models on two kinds of covariate. (a) NNLS deconvolution proportions, which require
  results/tables/c2l_signatures_mp.csv - a cell2location reference built by 13_reference_signatures.py
  --use-metaprograms (GPU regression). That file still carries the PRE-AUDIT families (its malignant column is
  'malignant_novel_MP15' where the corrected families name 'novel_MP9'), and regenerating it is spatial-track finding
  SP-06, which is not available. Re-running the NNLS path against the stale matrix would fit one programme and label it
  as another, so that path is NOT re-run here. (b) Rank scores over the metaprogram gene sets, which read
  results/tables/metaprogram_families.csv and metaprogram_genes.csv directly - both regenerated by the metaprogram
  track on 2026-10-19. Only path (b) is re-run.

Inputs : results/tables/openpedcan_dmg_cohort.csv (unchanged by the audit - built from histologies + independent
         specimens, no signature dependency), data/external/openpedcan_v14/gene-expression-rsem-tpm-collapsed.rds,
         results/tables/metaprogram_families.csv, results/tables/metaprogram_genes.csv.
Outputs (new filenames; nothing from the pre-audit run is overwritten):
         results/tables/openpedcan_rankscore_audit.csv   per-specimen rank score per corrected family
         results/tables/survival_rankscore_audit.csv     Cox results incl. proportional-hazards test (P7-07)
Models : per family - univariate; adjusted for age + pons (the pre-audit specification, kept); and a TP53 sensitivity
         model (P7-07: TP53 status is prognostic but was unmodelled). Schoenfeld PH test per fit. BH within model.
Run: python scripts/25b_survival_rankscore_audit.py
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import dmg_atlas.utils as U  # noqa: E402  (thread caps first)
import numpy as np, pandas as pd  # noqa: E402
import scipy.stats as ss  # noqa: E402
from dmg_atlas import RESULTS, LOGS, ROOT  # noqa: E402
import pyreadr  # noqa: E402
from lifelines import CoxPHFitter  # noqa: E402
from lifelines.statistics import proportional_hazard_test  # noqa: E402

TABLES = RESULTS / "tables"
EXT = ROOT / "data" / "external" / "openpedcan_v14"
log = U.StepLogger(LOGS / "fix_phase7.log", context="25b_survival_rankscore_audit")

with log.step("inputs"):
    cohort = pd.read_csv(TABLES / "openpedcan_dmg_cohort.csv")
    fm = pd.read_csv(TABLES / "metaprogram_families.csv").dropna(subset=["family"])
    mg = pd.read_csv(TABLES / "metaprogram_genes.csv")
    fams = sorted(fm.family.unique())
    log.write(f"cohort {cohort.shape}; corrected families {fams}; "
              f"metaprogram_genes {mg.shape} over {mg.metaprogram.nunique()} programmes")

with log.step("TPM + rank scores"):
    tpm = next(iter(pyreadr.read_r(EXT / "gene-expression-rsem-tpm-collapsed.rds").values()))
    ids = [b for b in cohort.Kids_First_Biospecimen_ID if b in tpm.columns]
    T = tpm[ids].astype(float); del tpm
    R = T.rank(axis=0) / len(T)
    out = pd.DataFrame(index=pd.Index(ids, name="Kids_First_Biospecimen_ID"))
    for fam, g in fm.groupby("family"):
        genes = [x for x in set(mg.gene[mg.metaprogram.isin(g.metaprogram)]) if x in R.index]
        out[f"rank:{fam}"] = R.loc[genes].mean().reindex(ids).values
        log.write(f"  {fam}: {len(genes)} genes in TPM from programmes {sorted(g.metaprogram)}")
    log.write(f"TPM {T.shape} for the cohort ({len(cohort) - len(ids)} specimens missing from the matrix)")

with log.step("Cox models + PH test"):
    d = cohort.set_index("Kids_First_Biospecimen_ID").join(out, how="inner")
    d = d[(d.excluded.fillna("") == "") & d.os_days.notna() & (d.os_days > 0)].copy()
    d["tp53"] = d.molecular_subtype.astype(str).str.contains("TP53").astype(int)
    desc = dict(n=len(d), events=int(d.os_event.sum()), median_os_days=float(d.os_days.median()),
                median_age_years=float(d.age_years.median()), pons=int(d.pons.sum()),
                tp53_known_frac=float(d.molecular_subtype.notna().mean()), tp53_positive=int(d.tp53.sum()))
    log.write("Cox cohort descriptors (P7-08): " + repr({k: (round(v, 3) if isinstance(v, float) else v) for k, v in desc.items()}))
    res = []
    for fam in fams:
        c = f"rank:{fam}"
        for model, cov in (("univariate", []), ("adjusted", ["age_years", "pons"]), ("tp53_sensitivity", ["age_years", "pons", "tp53"])):
            dd = d[["os_days", "os_event", c] + cov].dropna().copy()
            if dd[c].std() == 0 or len(dd) < 20:
                continue
            dd[c] = (dd[c] - dd[c].mean()) / dd[c].std()
            cph = CoxPHFitter().fit(dd, "os_days", "os_event")
            s = cph.summary.loc[c]
            ph = proportional_hazard_test(cph, dd, time_transform="rank")
            ph_p = float(ph.summary.loc[c, "p"])
            res.append(dict(variable_set="rank_score", variable=c, model=model, n=len(dd), events=int(dd.os_event.sum()),
                            hr_per_sd=float(s["exp(coef)"]), ci_lo=float(s["exp(coef) lower 95%"]),
                            ci_hi=float(s["exp(coef) upper 95%"]), p=float(s["p"]),
                            concordance=float(cph.concordance_index_), ph_p=ph_p, ph_violated=bool(ph_p < 0.05),
                            ph_p_global=float(ph.summary["p"].min())))
    res = pd.DataFrame(res)
    res["q_bh"] = np.nan
    for _, g in res.groupby("model"):
        res.loc[g.index, "q_bh"] = ss.false_discovery_control(g.p.values, method="bh")
    log.write("BH applied within model over the 7 families (pre-audit applied it within variable_set x model)")
    log.write(res[["variable", "model", "n", "events", "hr_per_sd", "ci_lo", "ci_hi", "p", "q_bh", "ph_p", "ph_violated"]].round(4).to_string(index=False))

with log.step("write"):
    o1 = TABLES / "openpedcan_rankscore_audit.csv"; o2 = TABLES / "survival_rankscore_audit.csv"
    assert not o1.exists() and not o2.exists(), "audit outputs already exist - refusing to overwrite"
    out.to_csv(o1); res.to_csv(o2, index=False)
    log.write(f"wrote {o1.name} ({out.shape}) and {o2.name} ({res.shape})")
log.write(f"done | peak RSS {U.peak_rss_gb():.2f} GB")
