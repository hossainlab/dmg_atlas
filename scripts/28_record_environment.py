#!/usr/bin/env python
"""Phase 8 / step 28 — record the software environments that produced the atlas (reproducibility, build-plan Phase 9.2).

Inputs : the running Python environment (conda env 'multiverse'), `conda list` of that env (if a conda executable is found via
         $CONDA_EXE or PATH), modal/singlecell_gpu_pyro191.py (Modal image pins), modal/built_env.json (image id),
         docs/phase7_multimodal_notes.md (extra pip packages installed inside Modal sandboxes are listed in EXTRA_MODAL below).
Outputs (env/, overwritten on every run — they describe the current environment):
  env/local_pip_freeze.txt      every installed distribution of the local env, 'name==version' (importlib.metadata)
  env/local_conda_list.txt      `conda list --explicit`-free `conda list` of the env (channel + build), if conda is available
  env/versions.csv              key packages: local version, Modal image pin, where each is used
  env/environment.md            generated summary: platform, hardware, Python, key versions, Modal image, thread caps
Run: python scripts/28_record_environment.py
"""
import os, re, sys, json, shutil, platform, subprocess, time
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import dmg_atlas.utils as U  # noqa: E402  (thread caps first)
import pandas as pd  # noqa: E402
from importlib import metadata  # noqa: E402
from dmg_atlas import ROOT, LOGS  # noqa: E402

log = U.StepLogger(LOGS / "phase8_release.log", context="28_record_environment")
ENV = ROOT / "env"
KEY = {  # distribution -> where it is used
    "numpy": "all", "scipy": "all", "pandas": "all", "anndata": "all h5ad I/O", "h5py": "chunked h5ad reads", "scanpy": "QC (incl. sc.pp.scrublet doublets), HVG, DE",
    "scikit-learn": "metrics, kNN, NMF", "statsmodels": "composition models", "matplotlib": "figures", "pyarrow": "parquet",
    "PyYAML": "configs", "requests": "downloads", "infercnvpy": "Phase 3 CNV", "leidenalg": "clustering",
    "igraph": "clustering", "umap-learn": "UMAP", "scvi-tools": "integration / query mapping (Modal)", "torch": "scVI, foundation models (Modal)",
    "cell2location": "spatial deconvolution (Modal)", "pyro-ppl": "cell2location backend (Modal)", "scgpt": "foundation embeddings (Modal)",
    "transformers": "Geneformer (Modal)", "lifelines": "Cox models (step 25)", "pyreadr": "OpenPedCan .rds (step 25)", "gdown": "scGPT weights (step 26)",
    "modal": "GPU / CPU sandboxes"}
EXTRA_MODAL = {"lifelines": "sandbox pip (step 25)", "pyreadr": "sandbox pip (step 25)", "gdown": "sandbox pip (step 26)",
               "transformers": "==4.46.3 sandbox pip (step 26)"}


def modal_pins() -> dict:
    txt = (ROOT / "modal/singlecell_gpu_pyro191.py").read_text()
    pins = {m.group(1): m.group(2) + m.group(3) for m in re.finditer(r'"([A-Za-z0-9_.\-]+)(==|~=|>=)([0-9][A-Za-z0-9_.]*)"', txt)}
    sha = re.search(r'_SCGPT_SHA = "([0-9a-f]+)"', txt)
    if sha:
        pins["scgpt"] = f"git {sha.group(1)[:12]}"
    pins["python"] = "3.11 (debian_slim)"
    return pins


with log.step("record environment"):
    ENV.mkdir(exist_ok=True)
    dists = sorted({(d.metadata["Name"], d.version) for d in metadata.distributions() if d.metadata["Name"]}, key=lambda x: x[0].lower())
    (ENV / "local_pip_freeze.txt").write_text("\n".join(f"{n}=={v}" for n, v in dists) + "\n")
    local = {n.lower().replace("_", "-"): v for n, v in dists}
    conda = os.environ.get("CONDA_EXE") or shutil.which("conda")
    if conda:
        r = subprocess.run([conda, "list", "-p", sys.prefix], capture_output=True, text=True)
        (ENV / "local_conda_list.txt").write_text(r.stdout if r.returncode == 0 else f"conda list failed: {r.stderr}")
    pins = modal_pins()
    rows = [dict(package=k, local=local.get(k.lower(), ""), modal=pins.get(k, EXTRA_MODAL.get(k, "")), used_for=u) for k, u in KEY.items()]
    rows.insert(0, dict(package="python", local=platform.python_version(), modal=pins["python"], used_for="all"))
    v = pd.DataFrame(rows)
    v.to_csv(ENV / "versions.csv", index=False)
    img = json.loads((ROOT / "modal/built_env.json").read_text())
    try:
        cpu = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True).stdout.strip()
        mem = int(subprocess.run(["sysctl", "-n", "hw.memsize"], capture_output=True, text=True).stdout.strip()) / 2**30
    except Exception:
        cpu, mem = platform.processor(), float("nan")
    lines = ["# Software environment — generated by scripts/28_record_environment.py (regenerate rather than hand-edit)", "",
             f"Generated {time.strftime('%Y-%m-%d %H:%M')}.", "",
             "## Local (CPU steps)", "",
             f"- Platform: {platform.platform()}; {cpu}; {mem:.0f} GB RAM.",
             f"- Python {platform.python_version()} at `{sys.prefix}` (conda env `multiverse`); {len(dists)} distributions "
             "(`env/local_pip_freeze.txt`" + (", `env/local_conda_list.txt`)." if conda else ")."),
             f"- Thread cap `DMG_ATLAS_THREADS` = {U.N_THREADS} (OMP / MKL / OpenBLAS / numba / vecLib), set by `dmg_atlas.utils`.", "",
             "## Modal (GPU / large-memory steps)", "",
             f"- Image `{img['image']}` (spec sha `{img['spec_sha']}`), defined in `modal/singlecell_gpu_pyro191.py`: debian_slim, Python 3.11, "
             "A10G for scVI / scANVI / cell2location / foundation models; 8-CPU / 64 GB sandboxes for steps 24–25 (`modal/phase6_cpu_run.py`).",
             "- Extra packages installed inside sandboxes at run time: " + "; ".join(f"{k} {v}" for k, v in EXTRA_MODAL.items()) + ".", "",
             "## Key packages", "", "| package | local | Modal | used for |", "|---|---|---|---|"]
    lines += [f"| {r.package} | {r.local or '—'} | {r.modal or '—'} | {r.used_for} |" for r in v.itertuples()]
    lines += ["", "Scripts that ran on Modal used the Modal versions (anndata 0.11 there vs the local version; `dmg_atlas.utils` disables "
              "pandas-3 Arrow strings so files written in either environment read in both).", ""]
    (ENV / "environment.md").write_text("\n".join(lines) + "\n")
    log.write(f"env/: {len(dists)} local distributions, {len(v)} key packages, conda list {'written' if conda else 'skipped'}")
log.write(f"done | peak RSS {U.peak_rss_gb():.2f} GB")
